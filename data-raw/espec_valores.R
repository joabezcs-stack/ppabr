# Especificação da camada harmonizada de valores (ppa_valores()).
#
# Para cada PPA, uma ou mais "partes"; cada parte lê uma tabela e devolve o valor total de
# cada programa por período. Campos de uma parte:
#   fonte   : tabela de origem
#   filtro  : expressão (texto) que deixa só as linhas que somam o total do programa sem
#             dupla contagem (linhas TOTAL do quadro, ou as parcelas, nunca as duas)
#   valores : colunas de valor = período ("2024", "2025-2027"; "ppa" = ciclo inteiro)
#   ano, valor : em vez de `valores`, para tabelas longas (uma coluna de ano e uma de valor)
#   mapa    : troca o sinônimo automático das colunas do programa (como em espec_programas.R)
#   escala  : multiplica os valores (1000 quando o documento está em R$ mil)
#   dedup   : TRUE quando a mesma linha de valor se repete (ex.: uma vez por indicador)
#   nivel   : "programa" (valor lido no quadro do programa) ou "acao" (somado das ações,
#             produtos, regiões ou fontes do programa)
#   parcial : TRUE quando o documento traz valores só de parte dos programas
# As linhas de cada parte são somadas por programa e período; partes diferentes de um PPA
# cobrem períodos ou programas diferentes. `revisada` = partes da versão revisada.

